// Exercicio 7: Calcule a área de um Triângulo.

alert("Área do Triângulo");

let baseTrinagulo = parseFloat(prompt("Informe o valor da base do triângulo em centímetros: "));

let alturaTriangulo = parseFloat(prompt("Informe o valor da altura do triângulo em centímetros: "));

alert ("A área total do triângulo de base" + baseTriangulo + "cm e altura" + alturaTriangulo + "cm é: " + (baseTrinagulo * alturaTriangulo) / 2 + "cm²");